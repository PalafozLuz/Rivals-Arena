CREATE OR REPLACE FUNCTION public.validar_inscricao_campeonato()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE
    campeonato public.campeonatos%ROWTYPE;
    quantidade INTEGER;
BEGIN
    SELECT * INTO campeonato FROM public.campeonatos
    WHERE id_campeonato = NEW.id_campeonato FOR UPDATE;

    IF campeonato.status NOT IN ('rascunho', 'aberto') THEN
        RAISE EXCEPTION 'O campeonato não está aceitando inscrições';
    END IF;

    SELECT count(*) INTO quantidade FROM public.inscricoes
    WHERE id_campeonato = NEW.id_campeonato
      AND status IN ('pendente', 'aprovada');

    IF quantidade >= campeonato.max_times THEN
        RAISE EXCEPTION 'O campeonato já atingiu o limite de times';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER validar_inscricao_antes BEFORE INSERT ON public.inscricoes
FOR EACH ROW EXECUTE FUNCTION public.validar_inscricao_campeonato();

CREATE OR REPLACE FUNCTION public.validar_partida_campeonato()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.id_time_a IS NOT NULL AND NOT EXISTS (
        SELECT 1 FROM public.inscricoes i
        WHERE i.id_campeonato = NEW.id_campeonato AND i.id_time = NEW.id_time_a AND i.status = 'aprovada'
    ) THEN RAISE EXCEPTION 'O time A não está inscrito no campeonato'; END IF;

    IF NEW.id_time_b IS NOT NULL AND NOT EXISTS (
        SELECT 1 FROM public.inscricoes i
        WHERE i.id_campeonato = NEW.id_campeonato AND i.id_time = NEW.id_time_b AND i.status = 'aprovada'
    ) THEN RAISE EXCEPTION 'O time B não está inscrito no campeonato'; END IF;

    IF NEW.status = 'finalizada' AND NEW.vencedor IS NULL THEN
        IF NEW.placar_a > NEW.placar_b THEN NEW.vencedor = NEW.id_time_a;
        ELSIF NEW.placar_b > NEW.placar_a THEN NEW.vencedor = NEW.id_time_b;
        END IF;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER validar_partida_antes BEFORE INSERT OR UPDATE ON public.partidas
FOR EACH ROW EXECUTE FUNCTION public.validar_partida_campeonato();

CREATE OR REPLACE FUNCTION public.processar_resultado_partida()
RETURNS TRIGGER LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE membro RECORD;
    pontos_a INTEGER;
    pontos_b INTEGER;
BEGIN
    IF NEW.status <> 'finalizada' OR NEW.resultado_processado
       OR NEW.id_time_a IS NULL OR NEW.id_time_b IS NULL THEN RETURN NEW; END IF;

    INSERT INTO public.classificacao_campeonatos (id_campeonato, id_time)
    VALUES (NEW.id_campeonato, NEW.id_time_a), (NEW.id_campeonato, NEW.id_time_b)
    ON CONFLICT DO NOTHING;

    IF NEW.placar_a > NEW.placar_b THEN pontos_a := 3; pontos_b := 0;
    ELSIF NEW.placar_b > NEW.placar_a THEN pontos_a := 0; pontos_b := 3;
    ELSE pontos_a := 1; pontos_b := 1;
    END IF;

    UPDATE public.classificacao_campeonatos c
    SET jogos = jogos + 1,
        vitorias = vitorias + CASE WHEN c.id_time = NEW.vencedor THEN 1 ELSE 0 END,
        derrotas = derrotas + CASE WHEN NEW.vencedor IS NOT NULL AND c.id_time <> NEW.vencedor THEN 1 ELSE 0 END,
        empates = empates + CASE WHEN NEW.vencedor IS NULL THEN 1 ELSE 0 END,
        pontos = pontos + CASE WHEN c.id_time = NEW.id_time_a THEN pontos_a ELSE pontos_b END,
        saldo_gols = saldo_gols + CASE WHEN c.id_time = NEW.id_time_a THEN NEW.placar_a - NEW.placar_b ELSE NEW.placar_b - NEW.placar_a END
    WHERE c.id_campeonato = NEW.id_campeonato AND c.id_time IN (NEW.id_time_a, NEW.id_time_b);

    FOR membro IN SELECT id_jogador, id_time FROM public.contratos
        WHERE id_time IN (NEW.id_time_a, NEW.id_time_b) AND status = 'ativo' AND data_saida IS NULL
    LOOP
        UPDATE public.jogadores
        SET pontuacao_ranking = pontuacao_ranking + CASE WHEN NEW.vencedor IS NULL THEN 5 WHEN membro.id_time = NEW.vencedor THEN 10 ELSE 2 END,
            vitorias = vitorias + CASE WHEN membro.id_time = NEW.vencedor THEN 1 ELSE 0 END,
            derrotas = derrotas + CASE WHEN NEW.vencedor IS NOT NULL AND membro.id_time <> NEW.vencedor THEN 1 ELSE 0 END
        WHERE id_jogador = membro.id_jogador;

        INSERT INTO public.historico_ranking (id_jogador, id_campeonato, id_partida, pontos, motivo)
        VALUES (membro.id_jogador, NEW.id_campeonato, NEW.id_partida,
            CASE WHEN NEW.vencedor IS NULL THEN 5 WHEN membro.id_time = NEW.vencedor THEN 10 ELSE 2 END,
            'Resultado de partida');
    END LOOP;

    NEW.resultado_processado = true;
    RETURN NEW;
END;
$$;

-- O prefixo zz garante que este trigger rode depois de validar_partida_antes
-- e receba o vencedor calculado quando o placar não for empate.
CREATE TRIGGER zz_processar_resultado BEFORE UPDATE ON public.partidas
FOR EACH ROW EXECUTE FUNCTION public.processar_resultado_partida();

-- Perfil automático criado junto com o usuário do Supabase Auth.
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE base_username TEXT; novo_username TEXT; numero INTEGER := 0;
BEGIN
    base_username := lower(regexp_replace(
        COALESCE(NULLIF(NEW.raw_user_meta_data ->> 'username', ''), 'jogador_' || left(replace(NEW.id::TEXT, '-', ''), 12)),
        '[^a-zA-Z0-9_]', '', 'g'));
    novo_username := left(base_username, 42);
    WHILE EXISTS (SELECT 1 FROM public.jogadores WHERE username = novo_username) LOOP
        numero := numero + 1;
        novo_username := left(base_username, 42) || '_' || numero;
    END LOOP;
    INSERT INTO public.jogadores (id_jogador, nome, username)
    VALUES (NEW.id, COALESCE(NULLIF(NEW.raw_user_meta_data ->> 'nome', ''), novo_username), novo_username);
    RETURN NEW;
END;
$$;

CREATE TRIGGER on_auth_user_created AFTER INSERT ON auth.users
FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

