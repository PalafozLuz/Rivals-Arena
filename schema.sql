CREATE TABLE public.jogadores (
    id_jogador UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    nome VARCHAR(100) NOT NULL DEFAULT '',
    username VARCHAR(50) NOT NULL UNIQUE,
    avatar_url TEXT,
    bio TEXT,
    pontuacao_ranking INTEGER NOT NULL DEFAULT 0 CHECK (pontuacao_ranking >= 0),
    vitorias INTEGER NOT NULL DEFAULT 0 CHECK (vitorias >= 0),
    derrotas INTEGER NOT NULL DEFAULT 0 CHECK (derrotas >= 0),
    data_cadastro TIMESTAMPTZ NOT NULL DEFAULT now(),
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE public.times (
    id_time BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL CHECK (length(trim(nome)) >= 2),
    logo_url TEXT,
    id_capitao UUID NOT NULL REFERENCES public.jogadores(id_jogador) ON DELETE CASCADE,
    status VARCHAR(20) NOT NULL DEFAULT 'ativo' CHECK (status IN ('ativo', 'inativo')),
    data_criacao TIMESTAMPTZ NOT NULL DEFAULT now(),
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE public.contratos (
    id_contrato BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_jogador UUID NOT NULL REFERENCES public.jogadores(id_jogador) ON DELETE CASCADE,
    id_time BIGINT NOT NULL REFERENCES public.times(id_time) ON DELETE CASCADE,
    data_entrada DATE NOT NULL DEFAULT CURRENT_DATE,
    data_saida DATE,
    status VARCHAR(20) NOT NULL DEFAULT 'ativo',
    CONSTRAINT contratos_status_valido CHECK (status IN ('ativo', 'inativo', 'pendente')),
    CONSTRAINT contratos_datas_validas CHECK (data_saida IS NULL OR data_saida >= data_entrada),
    CONSTRAINT contratos_status_consistente CHECK (
        (status = 'ativo' AND data_saida IS NULL)
        OR status IN ('inativo', 'pendente')
    )
);

CREATE UNIQUE INDEX contratos_jogador_ativo_unico
    ON public.contratos (id_jogador)
    WHERE status = 'ativo' AND data_saida IS NULL;
CREATE UNIQUE INDEX contratos_time_jogador_ativo_unico
    ON public.contratos (id_time, id_jogador)
    WHERE status = 'ativo' AND data_saida IS NULL;
CREATE INDEX contratos_time_idx ON public.contratos (id_time);

