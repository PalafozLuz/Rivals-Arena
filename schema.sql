    id_time BIGINT NOT NULL REFERENCES public.times(id_time) ON DELETE CASCADE,
    pontos INTEGER NOT NULL DEFAULT 0 CHECK (pontos >= 0),
    jogos INTEGER NOT NULL DEFAULT 0 CHECK (jogos >= 0),
    vitorias INTEGER NOT NULL DEFAULT 0 CHECK (vitorias >= 0),
    derrotas INTEGER NOT NULL DEFAULT 0 CHECK (derrotas >= 0),
    empates INTEGER NOT NULL DEFAULT 0 CHECK (empates >= 0),
    saldo_gols INTEGER NOT NULL DEFAULT 0,
    PRIMARY KEY (id_campeonato, id_time)
);

CREATE TABLE public.historico_ranking (
    id_historico BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_jogador UUID NOT NULL REFERENCES public.jogadores(id_jogador) ON DELETE CASCADE,
    id_campeonato BIGINT REFERENCES public.campeonatos(id_campeonato) ON DELETE SET NULL,
    id_partida BIGINT REFERENCES public.partidas(id_partida) ON DELETE SET NULL,
    pontos INTEGER NOT NULL,
