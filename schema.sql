CREATE TABLE public.campeonatos (
    id_campeonato BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL CHECK (length(trim(nome)) >= 3),
    jogo VARCHAR(100) NOT NULL CHECK (length(trim(jogo)) >= 2),
    descricao TEXT,
    formato VARCHAR(30) NOT NULL DEFAULT 'eliminatoria',
    max_times INTEGER NOT NULL CHECK (max_times BETWEEN 2 AND 1024),
    taxa_inscricao NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (taxa_inscricao >= 0),
    premio NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (premio >= 0),
    id_criador UUID NOT NULL REFERENCES public.jogadores(id_jogador) ON DELETE CASCADE,
    data_inicio DATE NOT NULL,
    data_fim DATE NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'rascunho',
    criado_em TIMESTAMPTZ NOT NULL DEFAULT now(),
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT campeonatos_formato_valido CHECK (formato IN ('eliminatoria', 'pontos_corridos', 'grupos')),
    CONSTRAINT campeonatos_status_valido CHECK (status IN ('rascunho', 'aberto', 'em_andamento', 'encerrado', 'cancelado')),
    CONSTRAINT campeonatos_datas_validas CHECK (data_fim >= data_inicio)
);

CREATE TABLE public.inscricoes (
    id_inscricao BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_time BIGINT NOT NULL REFERENCES public.times(id_time) ON DELETE CASCADE,
    id_campeonato BIGINT NOT NULL REFERENCES public.campeonatos(id_campeonato) ON DELETE CASCADE,
    data_inscricao TIMESTAMPTZ NOT NULL DEFAULT now(),
    status VARCHAR(20) NOT NULL DEFAULT 'pendente',
    CONSTRAINT inscricoes_status_valido CHECK (status IN ('pendente', 'aprovada', 'recusada', 'cancelada')),
    CONSTRAINT inscricoes_time_campeonato_unicos UNIQUE (id_time, id_campeonato)
);

CREATE INDEX inscricoes_campeonato_idx ON public.inscricoes (id_campeonato);

CREATE TABLE public.partidas (
    id_partida BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_campeonato BIGINT NOT NULL REFERENCES public.campeonatos(id_campeonato) ON DELETE CASCADE,
    rodada INTEGER NOT NULL CHECK (rodada > 0),
    numero_partida INTEGER NOT NULL CHECK (numero_partida > 0),
    id_time_a BIGINT REFERENCES public.times(id_time) ON DELETE SET NULL,
    id_time_b BIGINT REFERENCES public.times(id_time) ON DELETE SET NULL,
    placar_a INTEGER NOT NULL DEFAULT 0 CHECK (placar_a >= 0),
    placar_b INTEGER NOT NULL DEFAULT 0 CHECK (placar_b >= 0),
    vencedor BIGINT REFERENCES public.times(id_time) ON DELETE SET NULL,
    data_hora TIMESTAMPTZ,
    status VARCHAR(20) NOT NULL DEFAULT 'agendada',
    resultado_processado BOOLEAN NOT NULL DEFAULT false,
    CONSTRAINT partidas_status_valido CHECK (status IN ('agendada', 'em_andamento', 'finalizada', 'cancelada')),
    CONSTRAINT partidas_times_diferentes CHECK (id_time_a IS NULL OR id_time_b IS NULL OR id_time_a <> id_time_b),
    CONSTRAINT partidas_vencedor_valido CHECK (vencedor IS NULL OR vencedor IN (id_time_a, id_time_b)),
    CONSTRAINT partidas_chave_unica UNIQUE (id_campeonato, rodada, numero_partida)
);

CREATE INDEX partidas_campeonato_data_idx ON public.partidas (id_campeonato, data_hora);

CREATE TABLE public.classificacao_campeonatos (
